/**
 * Returns a randomized test session with the requested number of questions (10, 20, 30, or 50)
 */
export function generateTestQuestions(count: 10 | 20 | 30 | 50, gradeFilter?: number): TestQuestion[] {
  let pool = [...TEST_QUESTIONS_POOL];
  if (gradeFilter) {
    pool = pool.filter((q) => q.grade === gradeFilter);
  }

  // If pool is smaller than required, duplicate/pad pool with variation to ensure exact question count
  const result: TestQuestion[] = [];
  const shuffled = [...pool].sort(() => Math.random() - 0.5);

  for (let i = 0; i < count; i++) {
    const baseQuestion = shuffled[i % shuffled.length];
    result.push({
      ...baseQuestion,
      id: `gen-${i + 1}-${baseQuestion.id}`,
    });
  }

  return result;
}
